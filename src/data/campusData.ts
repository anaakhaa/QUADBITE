export function getCampusBadgeInfo(
  campusGroup: CampusPin['campusGroup']
): { label: string; className: string } {
  switch (campusGroup) {
    case 'Engineering Campus':
      return {
        label: 'Saintgits Engineering',
        className: 'bg-emerald-50 text-emerald-800 border border-emerald-300',
      };
    case 'Applied Sciences Campus':
      return {
        label: 'Saintgits Applied Sciences',
        className: 'bg-blue-50 text-blue-800 border border-blue-300',
      };
    case 'Shared Hostels & Grounds':
    default:
      return {
        label: 'Saintgits Hostels',
        className: 'bg-slate-100 text-slate-800 border border-slate-300',
      };
  }
}

